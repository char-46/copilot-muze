"""ControlService: one command/confirmation core shared by QQ, WebUI and CLI.

Frontends only differ in how they obtain input and deliver output; every
command, the agent, and the send-confirmation flow live here.

Command layer is plugin-style: handlers register themselves with the
``@slash`` decorator declaring usage/help, the help text is generated by
scanning the registry, and the framework guarantees every command produces a
reply (handlers may return a CommandOutcome, a plain str, a list of message
chains, or None — the framework wraps/兜底 accordingly).
"""

