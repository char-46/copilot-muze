    # ------------------------------------------------------------ qq route
    def is_control_ctx(self, ctx: ControlContext) -> bool:
        """Is this the controller's own session (where writes are allowed)?"""
        if ctx.is_local:
            return True  # cli / webui / console = the operator themself
        return is_control_conversation(self.cfg, ctx.scene, ctx.peer_id)

    def requires_approval(self, ctx: ControlContext) -> bool:
        """Reads are unconditional; writes outside the control session must
        be routed to the controller for approval."""
        return not self.is_control_ctx(ctx)

    def is_controller(self, scene: str, peer_id: int, sender_id: int) -> bool:
        """Is this sender allowed in this conversation?"""
        cfg = self.cfg.control
        if scene == "friend":
            return cfg.private_control and sender_id in cfg.controller
        if scene == "group":
            return bool(cfg.control_group) and peer_id == cfg.control_group and sender_id in cfg.controller
        return False

    def qq_should_trigger(
        self,
        scene: str,
        peer_id: int,
        sender_id: int,
        mention_self: bool,
        text: str,
        is_self: bool = False,
    ) -> bool:
        """Should this QQ message be treated as control input (command / LLM)?

        Isolation rules (multi-bot safe):
        - Only `/command` or `::llm message` ever trigger; plain chatter
          is archived but never answered.
        - Self-sent messages (this account talking from another client)
          never trigger — EXCEPT a true self-chat (peer == self). So when
          the controller IS one of the bots (controller contains self_id),
          the message it sends to another bot is answered by the receiving
          bot alone instead of both.
        - In groups with several bots present: @me -> only I answer;
          bare `/cmd` or `::msg` -> only the PRIMARY bot (first account)
          answers, so a controller message never gets N replies.
        """
        if is_self and peer_id != self.runtime.self_id:
            return False
        if not self.is_controller(scene, peer_id, sender_id):
            return False
        is_cmd = text.startswith("/") or (text.startswith(".") and len(text) > 1)
        is_llm = is_llm_invocation(text)
        if not (is_cmd or is_llm):
            return False
        if scene == "friend":
            return True
        if mention_self:
            return True  # explicitly addressed -> this bot answers
        return bool(getattr(self.runtime, "is_primary", True))


