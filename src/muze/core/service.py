    async def _session_pdf(self, session, ctx: ControlContext) -> CommandOutcome:
        """Render an agent session transcript (full loop incl. tool rounds)
        into a PDF file and send it back."""
        from muze.ai.sessions import legacy_final_tail
        from muze.render import render_pdf

        parts = [f"# 会话 #{session.id} {session.title}", "", f"> {session.prompt}", ""]
        messages = list(session.messages)
        if messages and messages[-1].get("role") != "assistant":
            tail = await legacy_final_tail(self.repo, session, self.runtime.self_id)
            if tail is not None:
                messages.append(tail)
        for m in messages:
            role = m.get("role", "")
            if role == "user":
                parts += ["**我**：", m.get("content", ""), ""]
            elif role == "assistant":
                content = m.get("content") or ""
                calls = m.get("tool_calls") or []
                head = "**muze**：" if content else "**muze**（调工具）"
                parts += [head, content, ""]
                for c in calls:
                    fn = c.get("function", {}) or {}
                    parts.append(f"`?? {fn.get('name', '?')}({fn.get('arguments') or ''})`")
                if calls:
                    parts.append("")
            elif role == "tool":
                parts += [f"<details-tool `{m.get('name', '')}`>", m.get("content") or "", ""]
        body = "\n".join(parts)
        try:
            pdf = await asyncio.to_thread(
                render_pdf, body, self._font_dir(),
                font_override=(self.cfg.reply.render_font or ""),
            )
        except Exception as e:
            return CommandOutcome.err(f"渲染失败: {e}")
        name = f"muze-sess-{session.id}.pdf"
        path = self._render_dir() / name
        path.write_bytes(pdf)
        if ctx.qq_reachable:
            try:
                await self.adapter.send_file(ctx.scene, ctx.peer_id, str(path), name)
            except ProtocolError as e:
                return CommandOutcome.err(f"PDF 已生成但发送失败（{path}）: {e}")
        return CommandOutcome(f"会话 #{session.id} 的 PDF 已生成并发送")

