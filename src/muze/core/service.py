        self.tunnel = None  # app-level SshTunnel, injected by main (/tun)
        self.rag_force = None  # forced indexing task (/rag run)
        self.rag_stop = None  # its stop event
        self.log_path = ""
        self.skills = None  # SkillStore, injected by main
