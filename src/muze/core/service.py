# command plugin registry
# --------------------------------------------------------------------------
@dataclass
class CommandSpec:
    name: str  # without slash
    usage: str  # e.g. "/search <关键词> [数量]"
    help: str  # one-line description for /help
    fn: Callable[..., Awaitable[object]]  # async (self, args, ctx) -> ...
    local_only: bool = False  # restricted to local fronts (cli/web/console)
    scope: str = "bot"  # "app": process-level (run once per process)
                         # "bot": operates on THIS account's data
    write: bool = False  # mutating / externally-visible (sends, schedule,
                         # memory writes, service state). Outside the
                         # controller's session these need approval.

    def help_line(self) -> str:
        u = self.usage or f"/{self.name}"
        if len(u) > 42:
            u = u[: 40] + "…"
        line = f"{u} - {self.help}" if self.help else u
        if self.local_only:
            line += " [本地]"
        if self.write:
            line += " [写]"
        return line


class CommandRegistry:
    def __init__(self) -> None:
        self._cmds: dict[str, CommandSpec] = {}

    def register(self, spec: CommandSpec) -> None:
        if spec.name in self._cmds:
            raise ValueError(f"duplicate command /{spec.name}")
        self._cmds[spec.name] = spec

    def get(self, name: str) -> CommandSpec | None:
        return self._cmds.get(name)

    def names(self) -> list[str]:
        return sorted(self._cmds)

    def all(self) -> list[CommandSpec]:
        return [self._cmds[n] for n in self.names()]

    def help_text(self) -> str:
        app = [s.help_line() for s in self.all() if s.scope == "app"]
        bot = [s.help_line() for s in self.all() if s.scope != "app"]
        head = "命令列表（scene/peer 形如 group/123 或 friend/456）:\n"
        sections = []
        if app:
            sections.append("── 应用级（作用于整个进程，与账号无关）──\n" + "\n".join(app))
        if bot:
            sections.append("── 本账号（作用于当前账号的数据）──\n" + "\n".join(bot))
        return head + "\n\n".join(sections)


COMMANDS = CommandRegistry()


def slash(
    name: str,
    usage: str = "",
    help: str = "",
    local_only: bool = False,
    scope: str = "bot",
    write: bool = False,
) -> Callable:
    """Declare a slash-command plugin on an async method.

    scope: "app"  — process-level command (config/code/lifecycle, account-
                    independent; with several bots in one chat only the
                    primary bot answers so it runs exactly once);
           "bot"  — operates on THIS account's archive/data (default).
    write: True for mutating / externally-visible commands (send, schedule,
           memory writes, service state). Such commands run directly in the
           controller's session (or local fronts) but are routed to the
           controller for approval anywhere else.
    The handler receives (self, args, ctx) and may return:
    CommandOutcome | str | list[list[dict]] (message chains) | None.
    The framework always converts that into a CommandOutcome reply.
    """

    def deco(fn):
        COMMANDS.register(
            CommandSpec(
                name=name, usage=usage, help=help, fn=fn,
                local_only=local_only, scope=scope, write=write,
            )
        )
        return fn

    return deco


def is_llm_invocation(text: str) -> bool:
    """LLM messages start with two colons (half/full width): `::` or `：：`."""
    return len(text) >= 2 and text[0] in ":：" and text[1] in ":："


def strip_llm_prefix(text: str) -> str:
    return text[2:].strip()


@dataclass
class ControlContext:
    source: str  # qq | web | cli
    chat_key: str  # stable per conversation, used for agent history
    scene: str  # control conversation scene (qq) or "" (web/cli)
    peer_id: int
    user_label: str = ""
    auto_confirm: bool = False  # CLI/local console sends immediately

    @property
    def is_local(self) -> bool:
        return self.source in ("cli", "web", "system")

    @property
    def qq_reachable(self) -> bool:
        return bool(self.scene)


@dataclass
class CommandOutcome:
    """A command reply.

    - text: plain text (sent as one message, optionally with media images)
    - media_paths: local image files to attach after the text
    - extra_chains: additional messages, each a raw Milky segment list —
      this is how commands emit message chains / multiple messages
    - is_error: marks the reply as an error for local fronts
    """

    text: str = ""
    media_paths: list[str] = field(default_factory=list)
    is_error: bool = False
    extra_chains: list[list[dict]] = field(default_factory=list)

    @classmethod
    def err(cls, text: str) -> "CommandOutcome":
        return cls(text=text, is_error=True)

    @classmethod
    def chains(cls, chains: list[list[dict]]) -> "CommandOutcome":
        return cls(extra_chains=list(chains))


class ControlService:
    def __init__(
        self,
        cfg: MuzeConfig,
        adapter: ProtocolAdapter,
        repo: Repository,
        chatlog: ChatLog,
        runtime: "Runtime",
    ) -> None:
        self.cfg = cfg
        self.adapter = adapter
        self.repo = repo
        self.chatlog = chatlog
        self.runtime = runtime
        self.agent = None  # injected after AI layer construction

    # ------------------------------------------------------------- helpers
    def parse_target(self, arg: str) -> tuple[str, int]:
        if "/" in arg:
            scene, _, peer = arg.partition("/")
        else:
            scene, peer = "friend", arg
        peer_i = int(peer)
        if scene not in ("friend", "group"):
            raise ValueError(f"unknown scene: {scene}")
        return scene, peer_i

    async def target_label(self, scene: str, peer: int) -> str:
        """Conversation label with lazily-resolved names."""
        if scene == "group":
            name = await self.adapter.ensure_group_name(peer)
            return f"{conv_id(scene, peer)} {name}".strip()
        name = await self.adapter.ensure_friend_name(peer)
        return f"{conv_id(scene, peer)} {name}".strip()

    # -------------------------------------------------------------- routes
    async def run_command(self, text: str, ctx: ControlContext | None = None) -> CommandOutcome:
        """Execute a command line (with or without leading slash). Commands
        only — never falls through to the agent. Used by the agent's `cli`
        tool so it can drive every command from a single tool schema.

        Framework guarantee: every invocation yields a CommandOutcome —
        handlers may return CommandOutcome/str/chains/None and all
        exceptions are converted into error replies.
        """
        line = (text or "").strip()
        if not line:
            return CommandOutcome.err("空命令")
        if line.startswith("."):  # "." is an accepted alias for "/"
            line = "/" + line[1:]
        if not line.startswith("/"):
            line = "/" + line
        if not ctx:
            ctx = ControlContext(source="system", chat_key="system", scene="", peer_id=0)
        try:
            parts = shlex.split(line)
        except ValueError:
            parts = line.split()
        cmd, args = parts[0][1:].lower(), parts[1:]

        spec = COMMANDS.get(cmd)
        if spec is None:
            return CommandOutcome.err(
                f"未知命令 /{cmd}。可用命令:\n{COMMANDS.help_text()}"
            )
        if spec.local_only and not ctx.is_local:
            return CommandOutcome.err(f"/{cmd} 仅限本地前端（console/WebUI/CLI）使用")
        try:
            raw = await spec.fn(self, args, ctx)
        except (ValueError, IndexError) as e:
            return CommandOutcome.err(
                f"参数错误: {e}\n用法: {spec.usage or '/' + spec.name}"
            )
        except ProtocolError as e:
            return CommandOutcome.err(f"协议端错误: {e}")
        except Exception as e:
            log.exception("command /%s crashed", cmd)
            return CommandOutcome.err(f"/{cmd} 执行出错: {e}")
        return self._coerce_reply(raw, cmd)

    @staticmethod
    def _coerce_reply(raw, cmd: str) -> CommandOutcome:
        """Normalize handler returns into a guaranteed CommandOutcome."""
        if raw is None:
            return CommandOutcome(f"/{cmd} 执行完成（无输出）")
        if isinstance(raw, CommandOutcome):
            if not (raw.text or raw.media_paths or raw.extra_chains):
                raw.text = f"/{cmd} 执行完成（无输出）"
            return raw
        if isinstance(raw, str):
            return CommandOutcome(raw)
        if isinstance(raw, list) and raw and isinstance(raw[0], list):
            return CommandOutcome.chains(raw)
        if isinstance(raw, dict):
            return CommandOutcome.chains([raw])
        return CommandOutcome(str(raw))

    def command_help(self) -> str:
        return COMMANDS.help_text()

    async def execute(self, text: str, ctx: ControlContext) -> CommandOutcome:
        text = (text or "").strip()
        if not text:
            return CommandOutcome.err("空输入")
        self.chatlog.ctrl(ctx.source, ctx.user_label or ctx.chat_key, text)

        if text.startswith("/") or (text.startswith(".") and len(text) > 1):
            return await self.run_command(text, ctx)

        # `::` (two colons, half/full width) -> the ONLY way to reach the LLM;
        # plain chatter never triggers the agent (command/LLM isolation).
        if is_llm_invocation(text):
            prompt = strip_llm_prefix(text)
            if not prompt:
                return CommandOutcome.err(":: 后面要有内容")
            if self.agent is None:
                return CommandOutcome.err(
                    "未配置 LLM（llm.chat.base_url/api_key/model）；命令仍可用，/help 查看"
                )
            # legacy muscle-memory: `::继续` now means `/sess go`
            if prompt in ("继续", "go", "接着"):
                return await self.cmd_sess(["go"], ctx)
            return await self.agent.converse(prompt, ctx)

        return CommandOutcome.err("未响应：命令以 / 或 . 开头；发给 AI 的内容以 :: 开头（两个冒号）")

    # ------------------------------------------------------------- sending
    async def deliver(self, ctx: ControlContext, outcome: CommandOutcome) -> None:
        """Send an outcome back into the QQ control conversation (if any).

        The main reply (text + media images) goes first, then each
        extra_chain is sent as its own message (multi-message replies).
        """
        if not ctx.qq_reachable:
            return
        messages: list[list[dict]] = []
        if outcome.text or outcome.media_paths:
            segments: list[dict] = []
            if outcome.text:
                segments.append(out_text(outcome.text[:3000]))
            for p in outcome.media_paths[:9]:
                segments.append(out_image(to_file_uri(p)))
            messages.append(segments)
        for chain in outcome.extra_chains[:9]:
            if chain:
                messages.append(chain)
        if not messages:
            return

        async def _send(segments: list[dict]) -> None:
            if ctx.scene == "group":
                await self.adapter.send_group_message(ctx.peer_id, segments)
            else:
                await self.adapter.send_private_message(ctx.peer_id, segments)

        try:
            for i, segs in enumerate(messages):
                await _send(segs)
                if i == 0:
                    self.chatlog.ctrl_reply(
                        ctx.source, ctx.user_label or ctx.chat_key, outcome.text
                    )
        except ProtocolError as e:
            log.warning("deliver to %s failed: %s", ctx.chat_key, e)

    async def send_as_bot(
        self, scene: str, peer_id: int, segments: list[dict], preview: str
    ) -> CommandOutcome:
        """Actually send a message as the controlled account; logs it."""
        if scene == "group":
            res = await self.adapter.send_group_message(peer_id, segments)
        else:
            res = await self.adapter.send_private_message(peer_id, segments)
        self.chatlog.sent(scene, peer_id, res.message_seq, preview)
        return CommandOutcome(f"已发送到 {await self.target_label(scene, peer_id)} (seq={res.message_seq})")

    async def request_send(
        self,
        scene: str,
        peer_id: int,
        segments: list[dict],
        preview: str,
        ctx: ControlContext,
        created_by: str,
    ) -> CommandOutcome:
        """Send now when allowed, otherwise route to the controller.

        Permission model: in the controller's own session (or a local front)
        writes are unconditional; ANYWHERE ELSE every outbound action must be
        approved by the controller, and the confirmation is delivered to the
        controller's control conversation — never back into the source chat.
        """
        if ctx.auto_confirm or self.is_control_ctx(ctx):
            return await self.send_as_bot(scene, peer_id, segments, preview)
        target = self.control_conversation()
        if target is None:
            return CommandOutcome.err(
                "无控制会话（请配置 control.controller 或 control.control_group），已拒绝发送"
            )
        ctrl_scene, ctrl_peer = target
        action_id = await self.repo.create_action(
            "send",
            scene,
            peer_id,
            {
                "segments": segments,
                "preview": preview[:500],
                "origin": f"{ctx.source}:{ctx.chat_key}",
            },
            ctrl_scene,
            ctrl_peer,
            created_by,
        )
        self.chatlog.confirm(
            action_id,
            f"pending send(from {ctx.source}:{ctx.chat_key}) -> {conv_id(scene, peer_id)}: {preview}",
        )
        await self.notify_controller(
            f"【审批请求 #{action_id}】来自 {ctx.source}:{ctx.chat_key}\n"
            f"拟以被控号向 {await self.target_label(scene, peer_id)} 发送:\n-----\n"
            f"{preview[:500]}\n-----\n/confirm {action_id} 批准，/cancel {action_id} 拒绝"
        )
        return CommandOutcome(
            f"待控制者确认 #{action_id}（该会话无写权限，已转交控制者）"
        )

    async def request_operation(
        self, tool: str, args: dict, ctx: ControlContext, description: str
    ) -> CommandOutcome:
        """Route a non-send write (memory, schedule, raw command) to the
        controller for approval when the caller is not in the control session."""
        target = self.control_conversation()
        if target is None:
            return CommandOutcome.err("无控制会话，已拒绝该操作")
        ctrl_scene, ctrl_peer = target
        action_id = await self.repo.create_action(
            "op",
            ctx.scene or "",
            ctx.peer_id or 0,
            {
                "tool": tool,
                "args": args,
                "origin": f"{ctx.source}:{ctx.chat_key}",
                "preview": description[:500],
            },
            ctrl_scene,
            ctrl_peer,
            "agent",
        )
        self.chatlog.confirm(action_id, f"pending op({tool}) from {ctx.source}:{ctx.chat_key}: {description}")
        await self.notify_controller(
            f"【审批请求 #{action_id}】来自 {ctx.source}:{ctx.chat_key}\n"
            f"操作: {description[:500]}\n/confirm {action_id} 批准，/cancel {action_id} 拒绝"
        )
        return CommandOutcome(f"待控制者确认 #{action_id}（{tool}，已转交控制者）")

    def control_conversation(self) -> tuple[str, int] | None:
        """Where approvals / notifications for this account are delivered."""
        if self.cfg.control.control_group:
            return "group", self.cfg.control.control_group
        if self.cfg.control.controller:
            return "friend", self.cfg.control.controller[0]
        return None

    async def notify_controller(self, text: str) -> None:
        target = self.control_conversation()
        if target is None:
            return
        scene, peer = target
        try:
            segs = [out_text(text[:1500])]
            if scene == "group":
                await self.adapter.send_group_message(peer, segs)
            else:
                await self.adapter.send_private_message(peer, segs)
        except ProtocolError as e:
            log.warning("notify controller failed: %s", e)

    async def execute_pending(self, action: dict, ctx: ControlContext) -> CommandOutcome:
        """Execute an approved pending action (kind: send | op)."""
        payload = json.loads(action["payload_json"])
        kind = action["kind"]
        if kind == "send":
            return await self.send_as_bot(
                action["scene"], action["peer_id"],
                payload.get("segments", []), payload.get("preview", ""),
            )
        if kind == "op":
            from muze.ai.tools import ToolRunner

            tool = payload.get("tool", "")
            targs = payload.get("args") or {}
            control_ctx = ControlContext(
                source="system", chat_key="system", scene="", peer_id=0,
                user_label="approved", auto_confirm=True,
            )
            runner = ToolRunner(
                self, self.repo, self.adapter, getattr(self.runtime, "llm", None), control_ctx
            )
            result = await runner.run(tool, targs)
            return CommandOutcome(f"已执行 {tool}: {str(result)[:800]}")
        return CommandOutcome.err(f"未知待办类型 {kind}")

    # ------------------------------------------------------------- commands
    @slash("schedule", "/schedule <时间> <指令>", "创建计划任务；时间: +秒数|ISO时间|every:秒数，如 /schedule +7200 总结未读", write=True)
    async def cmd_schedule(self, args: list[str], ctx: ControlContext) -> CommandOutcome:
        if len(args) < 2:
            return CommandOutcome.err(
                "用法: /schedule <时间> <指令>\n"
                "时间写法: +3600(1小时后) / 2026-09-30T09:00:00 / every:7200(每2小时)"
            )
        scheduler = self.runtime.scheduler
        if scheduler is None:
            return CommandOutcome.err("scheduler 未装配")
        spec, prompt = args[0], " ".join(args[1:])
        try:
            kwargs = self.parse_time_spec(spec)
        except ValueError as e:
            return CommandOutcome.err(f"时间格式错误: {e}")
        try:
            task = await scheduler.create(prompt=prompt, ctx=ctx, created_by="command", **kwargs)
        except ValueError as e:
            return CommandOutcome.err(str(e))
        return CommandOutcome(
            f"已创建计划任务 #{task['id']} [{task['kind']}]\n"
            f"下次执行: {epoch_iso(task['next_run_at'])}\n"
            f"指令: {prompt}\n结果将发送到 {conv_id(task['control_scene'], task['control_peer_id'])}"
        )

    @staticmethod
    def parse_time_spec(spec: str) -> dict:
        import re
        from datetime import datetime, timezone

        s = spec.strip().lower()
        m = re.fullmatch(r"every:(\d+)", s)
        if m:
            return {"interval_sec": int(m.group(1))}
        m = re.fullmatch(r"\+?(\d+)", s)
        if m:
            return {"delay_sec": int(m.group(1))}
        try:
            dt = datetime.fromisoformat(spec.strip())
        except ValueError:
            raise ValueError(f"无法解析时间: {spec}（支持 +秒 / every:秒 / ISO 时间）")
        if dt.tzinfo is None:
            dt = dt.astimezone()
        return {"at_ts": int(dt.timestamp())}

    @slash("tasks", "/tasks", "计划任务列表（含周期任务）")
    async def cmd_tasks(self, args: list[str], ctx: ControlContext) -> CommandOutcome:
        rows = await self.repo.list_tasks(active_only=False)
        if not rows:
            return CommandOutcome("没有计划任务；用 /schedule 或直接让 AI 创建")
        lines = []
        for r in rows[:30]:
            lines.append(
                f"#{r['id']} [{r['status']}/{r['kind']}] next={epoch_iso(r['next_run_at']) or '-'} "
                f"{'every ' + str(r['interval_sec']) + 's' if r['interval_sec'] else ''} "
                f"-> {conv_id(r['control_scene'], r['control_peer_id'])}: {r['prompt'][:60]}"
            )
        return CommandOutcome("\n".join(lines))

    @slash("canceltask", "/canceltask <id>", "取消计划任务", write=True)
    async def cmd_canceltask(self, args: list[str], ctx: ControlContext) -> CommandOutcome:
        if not args:
            return CommandOutcome.err("用法: /canceltask <id>")
        task_id = int(args[0])
        row = await self.repo.get_task(task_id)
        if not row or row["status"] != "active":
            return CommandOutcome.err(f"任务 #{task_id} 不存在或已结束")
        await self.repo.finish_task(task_id, "cancelled")
        return CommandOutcome(f"已取消任务 #{task_id}")

    @slash("read", "/read <文件路径>", "读取本地文档内容（docx/txt/md/html…，媒体已落盘路径可用）", scope="app")
    async def cmd_read(self, args: list[str], ctx: ControlContext) -> CommandOutcome:
        if not args:
            return CommandOutcome.err("用法: /read <文件路径>")
        from muze.docs import read_document

        path = " ".join(args)
        try:
            text = await asyncio.to_thread(read_document, path)
        except (FileNotFoundError, ValueError) as e:
            return CommandOutcome.err(str(e))
        return CommandOutcome(text[:3500])

    @slash("fetch", "/fetch <URL>", "抓取网页/在线文档链接的文本内容", scope="app")
    async def cmd_fetch(self, args: list[str], ctx: ControlContext) -> CommandOutcome:
        if not args:
            return CommandOutcome.err("用法: /fetch <URL>")
        from muze.docs import fetch_url

        try:
            text = await fetch_url(args[0])
        except Exception as e:
            return CommandOutcome.err(str(e))
        return CommandOutcome(text[:3500])

    @slash("dream", "/dream [night|now|日|周|月|list]", "层级做梦：night=补链(内置) now=今天 2026-W40=周 2026-09=月", write=True)
    async def cmd_dream(self, args: list[str], ctx: ControlContext) -> CommandOutcome:
        from muze.digest import local_date as _local_date

        sub = (args[0].lower() if args else "").strip()

        if sub == "list":
            rows = await self.repo.list_digests(limit=50)
            if not rows:
                return CommandOutcome("还没有任何做梦报告；/dream now 立即生成一次")
            tag = {"day": "日", "week": "周", "month": "月"}
            return CommandOutcome(
                "做梦报告:\n"
                + "\n".join(
                    f"{r['date']} [{tag.get(r.get('period', 'day'), '?')}] ({r['report_len']}字)"
                    for r in rows
                )
            )

        if sub in ("night", "now"):
            if self.agent is None or not self.agent.llm.configured:
                return CommandOutcome.err("LLM 未配置，无法做梦")
            from muze.digest import dream_night, run_digest

            try:
                if sub == "night":
                    text = await dream_night(
                        self.repo, self.agent.llm, self.cfg, self.chatlog,
                        adapter=self.adapter,
                    )
                else:
                    report = await run_digest(
                        self.repo, self.agent.llm, self.cfg, self.chatlog,
                        date=_local_date(), adapter=self.adapter,
                    )
                    text = f"[{_local_date()} 做梦报告]\n\n{report[:2800]}"
            except Exception as e:
                return CommandOutcome.err(f"做梦失败: {e}")
            return CommandOutcome(text[:3200])

        if sub:
            import re as _re

            if not _re.fullmatch(r"\d{4}-\d{2}-\d{2}|\d{4}-W\d{1,2}|\d{4}-\d{2}", sub):
                return CommandOutcome.err("格式: YYYY-MM-DD / YYYY-Www(周) / YYYY-MM(月)，或 night/now/list")
            row = await self.repo.get_digest(sub)
            if not row:
                return CommandOutcome.err(f"{sub} 没有做梦报告；/dream list 查看已有报告")
